#!/usr/bin/env python3
"""Build one classic Worker script from the shared count model sources."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
count = (ROOT / 'web/forecast-count.mjs').read_text()
handler = (ROOT / 'web/forecast-worker.mjs').read_text()
if re.search(r'^import ', count, re.M):
    raise SystemExit('Count model gained an import; update the worker bundler.')
count = re.sub(r'^export (?=(?:const|function)\b)', '', count, flags=re.M)
if re.search(r'^(?:import|export) ', count, re.M):
    raise SystemExit('Unsupported count model module syntax.')
expected_import = "import {prepareCountModel,installCountModels,validateCounts} from './forecast-count.mjs';\n"
if not handler.startswith(expected_import):
    raise SystemExit('Worker imports changed; update the worker bundler.')
bundle = '// Generated by tools/generate_forecast_worker.py; edit the source modules instead.\n' + count + '\n' + handler[len(expected_import):]
path = ROOT / 'web/forecast-worker-bundle.js'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not path.exists() or path.read_text() != bundle:
        raise SystemExit('Forecast worker bundle is stale. Run tools/generate_forecast_worker.py.')
else:
    path.write_text(bundle)
